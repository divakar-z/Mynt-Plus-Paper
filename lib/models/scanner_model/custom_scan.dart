import 'dart:convert';

class SavedCustomScan {
  final int id;
  final String name;
  final Map<String, dynamic> predicateJson;
  final String? createdBy;
  final String? createdAt;
  final String? lastRunAt;
  final int runCount;

  const SavedCustomScan({
    required this.id,
    required this.name,
    required this.predicateJson,
    required this.createdBy,
    required this.createdAt,
    required this.lastRunAt,
    required this.runCount,
  });

  factory SavedCustomScan.fromJson(Map<String, dynamic> j) => SavedCustomScan(
        id: (j['id'] as num).toInt(),
        name: j['name'] as String,
        // Backend serializes `predicate_json` as a JSON-encoded STRING on
        // the saved-scans list (raw column from the DB), but inlines it as
        // an object on `/scans/saved/{id}`. Decode either shape so the
        // shell can round-trip whichever endpoint we hit.
        predicateJson: _decodePredicate(j['predicate_json'] ?? j['predicate']),
        createdBy: j['created_by'] as String?,
        createdAt: j['created_at'] as String?,
        lastRunAt: j['last_run_at'] as String?,
        runCount: ((j['run_count'] ?? 0) as num).toInt(),
      );
}

Map<String, dynamic> _decodePredicate(Object? raw) {
  if (raw == null) return const {};
  if (raw is Map) return Map<String, dynamic>.from(raw);
  if (raw is String && raw.isNotEmpty) {
    try {
      final decoded = jsonDecode(raw);
      if (decoded is Map) return Map<String, dynamic>.from(decoded);
    } catch (_) {
      // Falls through to empty — the builder will treat it as a fresh
      // predicate. Better than crashing the whole list view on one bad
      // row.
    }
  }
  return const {};
}

class CustomScanColumn {
  final String key;
  final String label;
  const CustomScanColumn({required this.key, required this.label});

  factory CustomScanColumn.fromJson(Map<String, dynamic> j) =>
      CustomScanColumn(
        key: j['key'] as String,
        label: (j['label'] ?? j['key']) as String,
      );
}

class CustomScanMatch {
  final String ticker;
  final String name;
  /// Keyed by `CustomScanColumn.key` (e.g. `"rsi(14)"`, `"sma(close,50)"`).
  /// Values may be null when the indicator couldn't be computed for the
  /// symbol on the as-of date.
  final Map<String, num?> values;

  const CustomScanMatch({
    required this.ticker,
    required this.name,
    required this.values,
  });

  factory CustomScanMatch.fromJson(Map<String, dynamic> j) {
    final raw = (j['values'] as Map?) ?? const {};
    final values = <String, num?>{};
    raw.forEach((k, v) {
      if (v == null) {
        values[k.toString()] = null;
      } else if (v is num) {
        values[k.toString()] = v;
      } else {
        values[k.toString()] = num.tryParse(v.toString());
      }
    });
    return CustomScanMatch(
      ticker: j['ticker'] as String,
      name: (j['name'] ?? '') as String,
      values: values,
    );
  }
}

class CustomScanRunResult {
  final String asOf;
  /// Predicate-derived columns, in first-appearance order. Auto-generated by
  /// the server from the indicators referenced in the predicate tree.
  final List<CustomScanColumn> columns;
  final List<CustomScanMatch> matches;
  /// Per-index match counts when `include_index_counts=true` was sent.
  /// Map keys are index names from `/indices/market`. Empty when the
  /// backend hasn't shipped the feature yet — dropdown falls back to
  /// universe size.
  final Map<String, int> indexCounts;

  const CustomScanRunResult({
    required this.asOf,
    required this.columns,
    required this.matches,
    this.indexCounts = const {},
  });

  factory CustomScanRunResult.fromJson(Map<String, dynamic> j) {
    return CustomScanRunResult(
      asOf: (j['as_of'] ?? '') as String,
      columns: ((j['columns'] as List?) ?? const [])
          .cast<Map<String, dynamic>>()
          .map(CustomScanColumn.fromJson)
          .toList(),
      matches: ((j['matches'] as List?) ?? const [])
          .cast<Map<String, dynamic>>()
          .map(CustomScanMatch.fromJson)
          .toList(),
      indexCounts: _parseCustomIndexCounts(j['index_counts']),
    );
  }
}

Map<String, int> _parseCustomIndexCounts(Object? raw) {
  if (raw is! Map) return const {};
  final out = <String, int>{};
  raw.forEach((k, v) {
    if (v is num) out[k.toString()] = v.toInt();
  });
  return out;
}
